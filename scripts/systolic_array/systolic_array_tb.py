def append_matrix(file_path, matrix):
    """
    Append a 2-D matrix to a CSV file.
    Each row becomes one CSV line.
    Values are written as hex (0x????).
    """

    if not isinstance(matrix, np.ndarray):
        raise TypeError("matrix must be numpy.ndarray")

    if matrix.ndim != 2:
        raise ValueError("matrix must be 2-D")

    with open(file_path, "a") as f:
        for r in range(matrix.shape[0]):
            row = ",".join(f"0x{int(x):04X}" for x in matrix[r])
            f.write(row + "\n")
        f.write("\n")


def gen_matrix(height, width, dtype="bf16", *, seed=None, scale=1.0,
               device="cpu", fill_value=None):
    """
    Returns (height x width) matrix as np.uint16 raw encodings
    suitable for HW simulation.
    """

    if seed is not None:
        torch.manual_seed(seed)

    # Select target floating dtype
    if dtype == "bf16":
        out_dtype = torch.bfloat16
    elif dtype == "fp16":
        out_dtype = torch.float16
    else:
        raise ValueError("dtype must be 'bf16' or 'fp16'")

    # Generate in FP32 first
    if fill_value is None:
        mat_f32 = torch.randn(height, width, dtype=torch.float32,
                              device=device) * float(scale)
    else:
        mat_f32 = torch.full((height, width), float(fill_value),
                             dtype=torch.float32, device=device)

    # Cast with deterministic rounding
    mat = mat_f32.to(out_dtype)

    # Reinterpret bits as uint16
    mat = mat.view(torch.uint16)

    # Convert to numpy uint16 for simulator
    return mat.cpu().numpy()

def identity_matrix(height, width, dtype="bf16", *, device="cpu"):
    """
    Returns a (height x width) identity matrix in BF16 or FP16.
    Generate in FP32, then cast (deterministic rounding)
    Ones on the main diagonal up to min(height, width).
    """

    if dtype == "bf16":
        out_dtype = torch.bfloat16
    elif dtype == "fp16":
        out_dtype = torch.float16
    else:
        raise ValueError("dtype must be 'bf16', or 'fp16'")

    I_fp32 = torch.zeros(height, width, dtype=torch.float32, device=device)
    diag_len = min(height, width)

    for i in range(diag_len):
        I_fp32[i, i] = 1.0

    mat = I_fp32.to(out_dtype)

    # Reinterpret bits as uint16
    mat = mat.view(torch.uint16)

    # Return NumPy uint16 for simulator
    return mat.cpu().numpy()

def gen_matrix_fill_col(height, width, dtype="bf16", *, col_index,
                        seed=None,
                        device="cpu", one_value=1.0):

    if seed is not None:
        torch.manual_seed(seed)

    # Select dtype
    if dtype == "bf16":
        out_dtype = torch.bfloat16
    elif dtype == "fp16":
        out_dtype = torch.float16
    else:
        raise ValueError("dtype must be 'bf16' or 'fp16'")

    if col_index < 0 or col_index >= width:
        raise ValueError("col_index must be within [0, width-1]")

    # Base matrix
    mat_f32 = torch.zeros((height, width),
                          dtype=torch.float32,
                          device=device)

    # Fill column
    mat_f32[:, col_index] = float(one_value)

    # Cast + reinterpret bits
    mat = mat_f32.to(out_dtype)
    mat = mat.view(torch.uint16)

    return mat.cpu().numpy()

def gen_matrix_fill_row(height, width, dtype="bf16", *, row_index,
                        seed=None,
                        device="cpu", one_value=1.0):

    if seed is not None:
        torch.manual_seed(seed)

    # Select dtype
    if dtype == "bf16":
        out_dtype = torch.bfloat16
    elif dtype == "fp16":
        out_dtype = torch.float16
    else:
        raise ValueError("dtype must be 'bf16' or 'fp16'")

    if row_index < 0 or row_index >= width:
        raise ValueError("col_index must be within [0, width-1]")

    # Base matrix
    mat_f32 = torch.zeros((height, width),
                          dtype=torch.float32,
                          device=device)

    # Fill column
    mat_f32[row_index, :] = float(one_value)

    # Cast + reinterpret bits
    mat = mat_f32.to(out_dtype)
    mat = mat.view(torch.uint16)

    return mat.cpu().numpy()

