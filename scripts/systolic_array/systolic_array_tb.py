def sim_val_from_bits(bits, dtype="bf16"):
    if dtype == "bf16":
        return bf16_utils.bf16_from_bits(bits)
    elif dtype == "fp16":
        return fp16_utils.fp16_from_bits(bits)
    raise ValueError("dtype must be 'bf16' or 'fp16'")

def sim_add_hw(a: np.uint16, b: np.uint16, dtype="bf16") -> np.uint16:
    if dtype == "bf16":
        return np.uint16(bf16_utils.bf16_add_hw(a, b))
    elif dtype == "fp16":
        return np.uint16(fp16_utils.fp16_add_hw(a, b))
    raise ValueError("dtype must be 'bf16' or 'fp16'")

def sim_mul_hw(a: np.uint16, b: np.uint16, dtype="bf16") -> np.uint16:
    if dtype == "bf16":
        return np.uint16(bf16_utils.bf16_mul_hw(a, b))
    elif dtype == "fp16":
        return np.uint16(fp16_utils.fp16_mul_hw(a, b))
    raise ValueError("dtype must be 'bf16' or 'fp16'")

def sim_adder_tree_hw(vec: np.ndarray, Psum: np.uint16, dtype="bf16") -> np.uint16:
    # vec: shape (K,), dtype uint16
    if vec.size == 0:
        return np.uint16(Psum)

    level = vec.astype(np.uint16, copy=False)

    # balanced reduction
    while level.size > 1:
        n = level.size
        m = n // 2

        nxt = np.empty((m + (n & 1),), dtype=np.uint16)

        # pairwise adds
        for i in range(m):
            nxt[i] = sim_add_hw(level[2*i], level[2*i + 1], dtype)

        # carry last if odd
        if n & 1:
            nxt[m] = level[-1]

        level = nxt

    return sim_add_hw(level[0], Psum, dtype)

def sim_MEISSA_col(A_row: np.ndarray, B_col: np.ndarray, Psum: np.uint16, dtype="bf16") -> np.uint16:
    # A_row, B_col: shape (K,), dtype uint16
    if A_row.shape != B_col.shape:
        raise ValueError(f"A_row and B_col must match shapes, got {A_row.shape} vs {B_col.shape}")
    if A_row.dtype != np.uint16 or B_col.dtype != np.uint16:
        raise TypeError("A_row and B_col must be np.uint16 arrays of raw bits")

    K = A_row.size
    vec = np.empty((K,), dtype=np.uint16)

    for i in range(K):
        vec[i] = sim_mul_hw(A_row[i], B_col[i], dtype)

    return sim_adder_tree_hw(vec, np.uint16(Psum), dtype)


def sim_MEISSA(weight: np.ndarray, input: np.ndarray, psum: np.ndarray, dtype="bf16") -> np.ndarray:
    # A: (M,K), B: (K,N), C: (M,N) all uint16 raw bits
    if dtype not in ("bf16", "fp16"):
        raise ValueError("dtype must be 'bf16' or 'fp16'")

    if weight.dtype != np.uint16 or input.dtype != np.uint16 or psum.dtype != np.uint16:
        raise TypeError("A, B, C must be np.uint16 arrays of raw bits")

    M, K = input.shape
    K2, N = weight.shape
    if K != K2:
        raise ValueError(f"Inner dims must match: input is {input.shape}, weight is {weight.shape}")
    if psum.shape != (M, N):
        raise ValueError(f"psum must be shape {(M, N)}, got {psum.shape}")

    D = np.empty((M, N), dtype=np.uint16)

    for r in range(M):
        A_row = input[r, :]
        for c in range(N):
            B_col = weight[:, c]
            D[r, c] = sim_MEISSA_col(A_row, B_col, C[r, c], dtype)

    return D

